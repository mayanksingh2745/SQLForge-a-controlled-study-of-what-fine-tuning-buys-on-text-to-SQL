"""Data contracts for generation logs, evaluation metrics, and statistical benchmarks."""

from pydantic import BaseModel, ConfigDict, Field


class GenerationResult(BaseModel):
    """Raw inference generation output for an individual example."""

    model_config = ConfigDict(frozen=True)

    example_id: str = Field(..., description="Correlating TextToSQLExample ID")
    generated_sql: str = Field(..., description="Model generated SQL candidate query")
    prompt_tokens: int = Field(default=0, ge=0, description="Number of tokens in formatted prompt")
    completion_tokens: int = Field(default=0, ge=0, description="Tokens generated by model")
    latency_ms: float = Field(default=0.0, ge=0.0, description="Inference latency in milliseconds")
    finish_reason: str = Field(
        default="stop", description="Generation completion reason (e.g. 'stop', 'length')"
    )


class ConfidenceInterval(BaseModel):
    """Empirical bootstrap confidence interval bounds."""

    model_config = ConfigDict(frozen=True)

    lower: float = Field(..., ge=0.0, le=1.0, description="Lower bound")
    upper: float = Field(..., ge=0.0, le=1.0, description="Upper bound")
    confidence_level: float = Field(
        default=0.95, ge=0.5, le=1.0, description="Confidence level (e.g. 0.95 for 95%)"
    )


class EvaluationMetrics(BaseModel):
    """Aggregated evaluation metrics for an experiment evaluation run."""

    model_config = ConfigDict(frozen=True)

    total_examples: int = Field(..., ge=0, description="Total number of evaluated examples")
    valid_sql_rate: float = Field(
        ..., ge=0.0, le=1.0, description="Proportion of queries that parse and execute"
    )
    exact_match_accuracy: float = Field(
        ..., ge=0.0, le=1.0, description="Exact AST/string match with gold SQL"
    )
    execution_accuracy: float = Field(
        ..., ge=0.0, le=1.0, description="Execution equivalence with gold SQL result set"
    )
    syntax_error_rate: float = Field(
        default=0.0, ge=0.0, le=1.0, description="Proportion failing with SQL syntax errors"
    )
    timeout_rate: float = Field(
        default=0.0, ge=0.0, le=1.0, description="Proportion exceeding query timeout"
    )
    latency_p50_ms: float = Field(
        default=0.0, ge=0.0, description="Median generation latency in milliseconds"
    )
    latency_p95_ms: float = Field(
        default=0.0, ge=0.0, description="95th percentile generation latency in milliseconds"
    )
    bootstrap_ci_execution_accuracy: ConfidenceInterval | None = Field(
        default=None,
        description="95% bootstrap confidence interval for execution accuracy",
    )
    difficulty_breakdown: dict[str, float] = Field(
        default_factory=dict,
        description="Execution accuracy partitioned by query difficulty (easy, medium, hard, extra)",
    )
